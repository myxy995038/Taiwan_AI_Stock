from __future__ import annotations

import uuid
import time
from datetime import datetime

# ==============================================================================
# Divider
# ==============================================================================

def divider(char: str = "-", length: int = 70) -> None:
    """
    印出分隔線

    Example
    -------
    divider()

    ----------------------------------------------------------------------
    """
    print(char * length)


# ==============================================================================
# Banner
# ==============================================================================

def banner(title: str) -> None:
    """
    印出標題 Banner

    Example
    -------
    banner("Learning Engine")
    """

    divider("=")

    print(f"🚀 {title}")

    divider("=")


# ==============================================================================
# Section
# ==============================================================================

def section(title: str) -> None:
    """
    印出章節標題

    Example
    -------
    section("Load Weight")
    """

    print()
    divider("-")
    print(f"📌 {title}")
    divider("-")


# ==============================================================================
# Success
# ==============================================================================

def success(message: str) -> None:
    """
    成功訊息
    """

    print(f"✅ {message}")


# ==============================================================================
# Warning
# ==============================================================================

def warning(message: str) -> None:
    """
    警告訊息
    """

    print(f"⚠️ {message}")


# ==============================================================================
# Error
# ==============================================================================

def error(message: str) -> None:
    """
    錯誤訊息
    """

    print(f"❌ {message}")


# ==============================================================================
# Info
# ==============================================================================

def info(message: str) -> None:
    """
    一般資訊
    """

    print(f"ℹ️ {message}")


# ==============================================================================
# UUID
# ==============================================================================

def generate_uuid() -> str:
    """
    產生 UUID
    """

    return str(uuid.uuid4())


# ==============================================================================
# Timestamp
# ==============================================================================

def timestamp() -> str:
    """
    回傳目前時間

    Example
    -------
    2026-07-23 14:35:10
    """

    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")


# ==============================================================================
# Timer
# ==============================================================================

def now() -> float:
    """
    取得目前時間戳（供計時使用）
    """

    return time.perf_counter()


def elapsed(start_time: float) -> float:
    """
    計算耗時（秒）

    Parameters
    ----------
    start_time : float

    Returns
    -------
    float
    """

    return round(time.perf_counter() - start_time, 3)


# ==============================================================================
# Print Runtime
# ==============================================================================

def print_runtime(start_time: float, title: str = "Runtime") -> None:
    """
    印出執行時間

    Example
    -------
    ⏱ Learning Engine : 1.253 sec
    """

    sec = elapsed(start_time)

    print(f"⏱ {title} : {sec:.3f} sec")


# ==============================================================================
# Empty Line
# ==============================================================================

def blank(lines: int = 1) -> None:
    """
    印出空白行
    """

    for _ in range(lines):
        print()


